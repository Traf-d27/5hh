import React from "react";
import { X, AlertTriangle, ExternalLink, ShieldAlert, CheckCircle } from "lucide-react";
import { useCampus } from "../context/CampusContext";
import { formatInr } from "../utils/formatters";

export function DiscrepancyModal({ isOpen, onClose }) {
  const { settings } = useCampus();

  if (!isOpen) return null;

  const tariff = settings?.electricityTariffInr || 8.5;
  const expectedMonthlyKwh = 800 * 30; // 24,000 kWh/month
  const reconciledMonthlyInr = expectedMonthlyKwh * tariff; // ₹2,04,000/month
  const reconciledAnnualInr = reconciledMonthlyInr * 12; // ₹24,48,000/year

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-sm animate-in fade-in duration-200">
      <div className="bg-white rounded-2xl shadow-2xl border border-amber-300 max-w-lg w-full overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between p-5 border-b border-amber-100 bg-amber-50">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-amber-500 text-white flex items-center justify-center shadow-md shadow-amber-500/20">
              <ShieldAlert className="w-5 h-5" />
            </div>
            <div>
              <h3 className="font-extrabold text-slate-900 text-base">Published Solar Savings Discrepancy Audit</h3>
              <p className="text-xs text-amber-800 font-medium">Presidency University Official Reference Audit</p>
            </div>
          </div>
          <button onClick={onClose} className="text-slate-400 hover:text-slate-600 p-1.5 rounded-lg transition-colors">
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="p-6 space-y-4 text-xs leading-relaxed text-slate-600">
          <div className="p-3.5 rounded-xl bg-rose-50 border border-rose-200 text-rose-900 space-y-1">
            <div className="font-bold flex items-center gap-1.5 text-sm">
              <AlertTriangle className="w-4 h-4 text-rose-600" />
              Critical Mathematical Inconsistency Flagged
            </div>
            <p>
              The university official renewable energy portal reports approximately <strong>800 units (kWh) daily</strong> generated by rooftop solar panels on the Central Administration Building. However, the portal simultaneously reports an annualized/monthly financial savings figure that <strong>does not mathematically reconcile</strong> with this generation baseline.
            </p>
          </div>

          <div className="space-y-2">
            <div className="font-bold text-slate-900 uppercase tracking-wider text-[11px]">
              Empirical Reconciliation Calculation (Bescom Tariff @ ₹{tariff.toFixed(2)}/kWh):
            </div>
            <div className="grid grid-cols-2 gap-2 p-3 rounded-xl bg-slate-50 border border-slate-200">
              <div>
                <span className="text-slate-400 block text-[10px]">Daily Reference</span>
                <span className="font-bold text-slate-800 text-sm">800 kWh/day</span>
              </div>
              <div>
                <span className="text-slate-400 block text-[10px]">Monthly Generation</span>
                <span className="font-bold text-slate-800 text-sm">24,000 kWh/mo</span>
              </div>
              <div>
                <span className="text-slate-400 block text-[10px]">Reconciled Monthly Yield</span>
                <span className="font-extrabold text-emerald-700 text-sm">{formatInr(reconciledMonthlyInr)}</span>
              </div>
              <div>
                <span className="text-slate-400 block text-[10px]">Reconciled Annual Yield</span>
                <span className="font-extrabold text-emerald-700 text-sm">{formatInr(reconciledAnnualInr)}</span>
              </div>
            </div>
          </div>

          <div className="p-3.5 rounded-xl bg-emerald-50 border border-emerald-200 text-emerald-900 space-y-1">
            <div className="font-bold flex items-center gap-1.5">
              <CheckCircle className="w-4 h-4 text-emerald-600" />
              ECHOTECH Data Governance Decision:
            </div>
            <p>
              In adherence to strict hackathon data integrity rules, ECHOTECH <strong>refuses to use the unverified published monthly figure</strong> in financial analytics. Instead, we use the verifiable <strong>800 kWh/day physical generation baseline</strong> multiplied by the configurable campus electricity tariff (₹{tariff.toFixed(2)}/kWh).
            </p>
          </div>

          <div className="pt-2 text-[11px] text-slate-400 flex items-center justify-between border-t border-slate-100">
            <span>Source: presidencyuniversity.in/renewable--</span>
            <a
              href="https://presidencyuniversity.in/renewable--"
              target="_blank"
              rel="noreferrer"
              className="text-emerald-700 font-bold inline-flex items-center gap-1 hover:underline"
            >
              Verify Source <ExternalLink className="w-3 h-3" />
            </a>
          </div>
        </div>

        <div className="p-4 bg-slate-50 border-t border-slate-100 flex justify-end">
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-xl bg-slate-900 hover:bg-slate-800 text-white font-bold text-xs transition-colors"
          >
            Acknowledge Audit Notice
          </button>
        </div>
      </div>
    </div>
  );
}
